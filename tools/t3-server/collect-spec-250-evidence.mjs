#!/usr/bin/env node
/**
 * Spec 250 phase 11 — fill the acceptance evidence's numbers from the machine-readable runs.
 *
 * Alongside `collect-phase10-evidence.mjs`, and for the same reason: the prose in
 * `codev/resources/250-acceptance-evidence.md` is judgement and stays hand-written,
 * but the NUMBERS in it are exactly the kind that rot. A hand-typed "3 of 35
 * files conflict" is true on the day it is typed and silently wrong after the
 * next drill, and it is the sentence a reader will quote.
 *
 * So the numbers live between markers and are regenerated from the evidence
 * files the tools actually wrote:
 *
 *   codev/research/250-rebase-drill.json           tools/t3-fork/rebase-drill.mjs
 *   codev/research/250-criterion-8b-evidence.json  tools/t3-fork/criterion-8b.mjs
 *   codev/research/250-hierarchy-wire-evidence.json  packages/t3-client/live/spec-250-hierarchy.mjs
 *
 * Usage:
 *   node tools/t3-server/collect-spec-250-evidence.mjs [--check]
 *
 * `--check` regenerates in memory and fails if the file on disk differs — what
 * CI runs, so the committed evidence cannot drift from the runs it describes.
 *
 * Exit 3 — not 1 — when a run is missing or unreadable. "I could not read the
 * evidence" and "the evidence says the run failed" are different facts, and this
 * script never gets to make the second claim on the strength of the first.
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const target = join(repoRoot, 'codev', 'resources', '250-acceptance-evidence.md');
const BEGIN = '<!-- spec-250-evidence:begin -->';
const END = '<!-- spec-250-evidence:end -->';
const UNREADABLE = 3;

const checkOnly = process.argv.includes('--check');

function fail(message) {
  console.error(`[collect-spec-250-evidence] ${message}`);
  process.exit(UNREADABLE);
}

function read(relative) {
  const path = join(repoRoot, relative);
  if (!existsSync(path)) {
    fail(`MISSING_RUN: ${relative} does not exist. The run that writes it has not happened, or `
      + 'wrote somewhere else. This is not "the run failed".');
  }
  try {
    return JSON.parse(readFileSync(path, 'utf8'));
  } catch (error) {
    fail(`UNREADABLE_RUN: ${relative} is not readable JSON (${error.message}). Nothing is claimed `
      + 'about what it would have said.');
  }
  return null;
}

const drill = read('codev/research/250-rebase-drill.json');
const criterion8b = read('codev/research/250-criterion-8b-evidence.json');
const wire = read('codev/research/250-hierarchy-wire-evidence.json');
const pin = read('packages/types/src/t3/pin.json');

/**
 * A run that describes a different fork than the one pinned is STALE, and stale
 * evidence is worse than none: it is the same shape as fresh evidence and reads
 * as current. Both files already assert this internally; this is the third place
 * it is checked, because it is the one a reader looks at.
 */
for (const [name, evidence] of [['criterion-8b', criterion8b], ['hierarchy wire', wire]]) {
  if (evidence.forkCommit !== pin.commit) {
    fail(`STALE_RUN: the ${name} evidence describes fork ${String(evidence.forkCommit).slice(0, 12)} `
      + `and the pin is ${String(pin.commit).slice(0, 12)}. Re-run it rather than publishing a `
      + 'number about a fork that is not this one.');
  }
}
if (drill.forkHead !== pin.commit) {
  fail(`STALE_RUN: the rebase drill describes fork ${String(drill.forkHead).slice(0, 12)} and the `
    + `pin is ${String(pin.commit).slice(0, 12)}.`);
}

const surface = drill.wholeSurface?.conflictedFiles ?? [];
const watermark = drill.watermark ?? {};
const churn = drill.upstreamChurn ?? {};
const sourceHash = drill.contractClosure?.sourceHash ?? {};

/**
 * `null` is "the drill could not count", `0` is "there was nothing to count".
 * The collector must not render them the same way — that is the same defect the
 * exit codes above exist to avoid, one layer up.
 */
const counted = (n) => (typeof n === 'number' ? String(n) : '**not counted**');

/**
 * What the rebased tree would hand the generator, and — separately — whether the
 * generator was ever run on it. The second is always "no", and it is printed
 * rather than omitted so a reader cannot infer a shape-check from the silence.
 */
const closureMoved = sourceHash.checked
  ? (sourceHash.moved?.length
    ? `**${sourceHash.moved.length} of ${(drill.contractClosure?.files ?? []).length}**: `
      + `${sourceHash.moved.map((f) => `\`${f}\``).join(', ')}`
    : 'none — the rebased tree regenerates the contract already vendored')
  : `**not checked** — ${sourceHash.reason ?? 'no reason recorded'}`;

const lines = [
  BEGIN,
  '',
  `_Generated by \`tools/t3-server/collect-spec-250-evidence.mjs\` from the runs named above._`,
  '',
  '| Measurement | Value | From |',
  '|---|---|---|',
  `| fork pinned at | \`${String(pin.commit).slice(0, 12)}\` | \`pin.json\` |`,
  `| upstream base | \`${String(pin.upstreamBase).slice(0, 12)}\` | \`pin.json\` |`,
  `| drill target | \`${String(drill.target).slice(0, 12)}\` (\`${drill.targetRef}\`) | rebase drill |`,
  `| drill outcome | \`${drill.outcome}\` | rebase drill |`,
  `| customization commits carried | ${drill.commitsCarried} | rebase drill |`,
  `| sequential rebase stops at | ${drill.stoppedAt ? `\`${drill.stoppedAt}\`, on ${(drill.conflictedFiles ?? []).join(', ')}` : 'did not stop'} | rebase drill |`,
  `| whole conflict surface | **${surface.length}** file${surface.length === 1 ? '' : 's'}${surface.length ? `: ${surface.map((f) => `\`${f}\``).join(', ')}` : ''} | rebase drill |`,
  `| upstream commits in the range | ${counted(churn.commits)} | rebase drill |`,
  `| of those, touching the pinned closure | ${counted(churn.closureTouching)} | rebase drill |`,
  `| regeneration blocked by the rebase | ${drill.contractClosure?.regenerationReachable ? 'no — zero closure conflicts' : '**yes** — the generator\'s own source conflicts'} | rebase drill |`,
  `| closure files the rebased tree would change | ${closureMoved} | rebase drill |`,
  `| contract regenerated / \`shape-check\` run on the rebased tree | ${drill.contractRegeneration?.attempted ? 'yes' : '**no** — see the drill header'} | rebase drill |`,
  `| watermark at base | ${watermark.watermarkAtBase ?? 'unknown'} | rebase drill |`,
  `| migrations upstream added | ${(watermark.addedByUpstream ?? []).join(', ') || 'none'} | rebase drill |`,
  `| any shadowed (would be skipped) | ${watermark.checked ? (watermark.shadowed?.length ? `**${watermark.shadowed.join(', ')}**` : 'none') : '**not checked**'} | rebase drill |`,
  `| preserved upstream unmoved | ${drill.preserved?.upstreamStillAtBase ? 'yes' : '**no**'} | rebase drill |`,
  `| \`pin.commit\` unchanged by the drill | ${drill.preserved?.pinCommitUnchanged ? 'yes' : '**no**'} | rebase drill |`,
  `| criterion 8b | ${criterion8b.passed ? 'passed' : '**failed**'} | \`criterion-8b.mjs\` |`,
  `| criterion 11 wire evidence | ${wire.passed ? 'passed' : '**failed**'} | \`spec-250-hierarchy.mjs\` |`,
  '',
  END,
];
const block = lines.join('\n');

const current = readFileSync(target, 'utf8');
const begin = current.indexOf(BEGIN);
const end = current.indexOf(END);
if (begin === -1 || end === -1) {
  fail(`NO_MARKERS: ${target} has no ${BEGIN} / ${END} pair. Refusing to guess where the block `
    + 'goes — appending it somewhere would produce a second, contradictory table.');
}
const next = current.slice(0, begin) + block + current.slice(end + END.length);

if (checkOnly) {
  if (next !== current) {
    console.error('[collect-spec-250-evidence] the committed evidence does not match the runs it '
      + 'describes. Re-run without --check.');
    process.exit(1);
  }
  console.error('[collect-spec-250-evidence] evidence is up to date');
  process.exit(0);
}

writeFileSync(target, next);
console.error(`[collect-spec-250-evidence] filled the evidence block in ${target}`);
