#!/usr/bin/env node
/**
 * Spec 250 phase 11 — the rebase drill, as a PROCEDURE rather than an event.
 *
 * ## What it proves, and what it deliberately does not
 *
 * Criterion 9 asks whether the customization can be carried onto a later
 * upstream: whether the rebase completes, whether the contract regenerates from
 * the rebased fork, and whether `shape-check` still holds. It is met **by this
 * running and reporting**, not by adopting a new base.
 *
 * The drill answers the first question by running it and the second by measuring
 * its inputs. It does NOT answer the third, and the section below says so in the
 * place a reader would otherwise assume it did.
 *
 * ## Nothing real moves. That is the point, and it was ruled.
 *
 *   `/Users/chris/dev/t3code`       the PRESERVED upstream clone. Read-only.
 *                                   Fetch is fine — remote-tracking refs move
 *                                   and HEAD does not. A checkout is not.
 *   `/Users/chris/dev/t3code-codev` the fork. Read-only here.
 *   `pin.json`                      NOT advanced.
 *
 * The moment `pin.json` names a new base, `verify-upstream` expects the
 * preserved clone to BE there, and every spec 146 and spec 236 result tied to
 * `082e6ea52186` stops being re-runnable. Advancing the base is a decision taken
 * when there is a reason — a security fix, a feature we need — never as a phase
 * deliverable. So the drill runs in a **scratch clone** and throws it away.
 *
 * ## Every failure is reported, and the kinds are kept apart
 *
 * A drill that cannot run and a drill that ran and found conflicts are different
 * facts wanting different next actions, and reporting the first as the second
 * would be this project's recurring defect on the one tool whose job is to say
 * what happened. So:
 *
 *   ok                 every customization commit replayed with no conflicts
 *   conflicts          the rebase stopped on conflicts. THIS IS A RESULT, not an
 *                      error — it is the number the drill exists to produce, and
 *                      the files are listed
 *   could-not-run      no scratch, no clone, no upstream target. NOTHING was
 *                      learned, and it must never read as "no conflicts"
 *
 * ## What `ok` does NOT say, and why the vocabulary is exactly three words
 *
 * An earlier draft of this header defined `ok` as "rebase clean, contract
 * regenerated, shape-check held" and listed `regenerate-failed` and
 * `shape-check-failed` beside it. At the time the drill ran neither step, and
 * neither outcome was ever assigned anywhere in this file. The contract was
 * described as regenerated by a comment rather than by a generator — this
 * project's own recurring defect, a claim spelled the same way whether or not
 * anything checked it, sitting on the one tool whose subject is that
 * distinction.
 *
 * The drill regenerates now (see below), and the vocabulary is STILL three
 * words, deliberately. `outcome` describes the REBASE. A contract that
 * regenerates into something different is not a failed rebase, it is the cost of
 * adopting the base — so it is reported in `contractRegeneration` with the
 * artifact list, exactly as `conflicts` reports the file list. A test holds the
 * documented set and the assignable set together, so this cannot drift again.
 *
 * ## Regeneration IS proved, in the throwaway, and here is why that needed a
 * ## second scratch rather than the obvious call
 *
 * `generate.mjs` refuses any checkout whose `HEAD` is not `pin.commit`, and no
 * rebased tree can satisfy that: its head is a commit that did not exist before
 * the rebase. Pointed at the real repository, "regenerate from the rebased tree"
 * therefore means moving the real pin, which is the adoption this drill exists in
 * order NOT to perform. That is why the first version of this file only measured
 * the generator's INPUTS and said, correctly, that shape-check had not run.
 *
 * It leaves criterion 9 proving that the rebase measures, not that the contract
 * still regenerates after one — and the second is the claim that matters on the
 * day a new base is adopted, which is the worst possible moment to find out it
 * does not hold. So the drill now proves it, without touching anything real:
 *
 *   1. `git merge-tree --write-tree` writes the merged tree as an object, and
 *      `git commit-tree` makes it a commit IN THE THROWAWAY CLONE. Conflicted
 *      files carry markers; none of them is in the closure, and if one ever is,
 *      the generator fails and that failure is the reported result.
 *   2. A SCRATCH CODEGEN ROOT is assembled beside it: `generate.mjs` resolves
 *      every path from its own location, so a copy of the tool under a scratch
 *      directory reads a scratch `pin.json` and writes to a scratch
 *      `generated/`. The scratch pin names the merged commit, so the guard is
 *      satisfied honestly rather than bypassed.
 *   3. The generator runs. Then its output is compared, byte for byte, to the
 *      artifacts actually vendored in this repository.
 *
 * The real `pin.json` is not written and not read for this. Both real checkouts
 * are untouched, and the read-only order is still re-checked afterwards.
 *
 * A regenerated contract that DIFFERS is a result, not a failure — the same
 * argument as `conflicts`. It is the answer to "what would adopting this base
 * cost", and it is reported with the artifact list rather than as an error.
 *
 * `contractRegeneration.attempted` is `false`, with a reason, whenever there was
 * no tree to generate from — and `could-not-run` carries none of these fields at
 * all, deliberately: it means NOTHING was learned, so a measurement-shaped field
 * on it would be the first thing a reader mistook for a finding.
 *
 * ## The interpreter is not inherited from PATH
 *
 * The generator imports the closure's TypeScript directly and needs Node's type
 * stripping, so **Node 22 or newer**. The drill itself runs fine under 20. When
 * the interpreter cannot run the generator this reports `attempted: false` with
 * `NO_INTERPRETER` — never "the contract does not regenerate", which is a claim
 * about the fork rather than about this machine. `T3_CODEGEN_NODE` overrides.
 *
 * Usage:
 *   node tools/t3-fork/rebase-drill.mjs [--onto <ref>] [--out <file>] [--keep]
 *
 * `--onto` defaults to the upstream clone's `origin/main`. `--keep` leaves the
 * scratch for inspection and prints where it is.
 *
 * Exit codes: 0 ok or conflicts (both are results), 3 could-not-run.
 */

